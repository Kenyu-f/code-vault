// ============================================================================
// 設計セクション: 外部モジュールのインポート
// ============================================================================
// [設計意図] 標準入出力（I/O）機能を提供するモジュールをスコープに導入する。
// [詳細仕様] フルパス「std::io::stdin()」の記述を省略し、コードの可読性を
//            向上させるために「use」キーワードを使用してショートカットを作成する。
use std::io;

// ============================================================================
// 設計セクション: エントリーポイント
// ============================================================================
// [設計意図] OSから最初に呼び出されるプログラムの実行起点（main関数）を定義する。
fn main() {

    // ------------------------------------------------------------------------
    // 仕様1: 1つ目の数値の入力とデータ変換
    // ------------------------------------------------------------------------
    
    // [画面出力] ユーザーに最初の入力を促すプロンプトを表示する。
    // ※「println!」マクロは文字列の末尾に自動で改行コードコード（\n）を付与する。
    println!("Enter the first number:");

    // [バッファ確保] キーボードからの文字列を受け取るためのメモリ領域（器）を生成する。
    // ・「let」: 新しい変数の宣言を行う。
    // ・「mut」: Rustは規定で不変（再代入不可）なため、入力データを後から流し込んで
    //            内部状態を書き換えられるように「可変（mutable）」属性を強制する。
    // ・「String::new()」: ヒープメモリ上にサイズ可変の空の文字列オブジェクトを生成する。
    let mut input1 = String::new();

    // [標準入力の実行] ユーザーのキーボード入力をバッファに読み込む。
    // ・「io::stdin()」: 現在のプロセスの標準入力ストリームのハンドルを取得する。
    // ・「.read_line()」: エンターキー（改行）が押されるまで入力を待ち、値をバッファに書き込む。
    // ・「&mut input1」: 変数の中身を関数内で直接書き換える権利を与えるため、
    //                     input1への「可変の参照（ポインタ）」を引数として貸し出す。
    // ・「.unwrap()」: 物理的な入力エラー等で戻り値の「Result型」が失敗（Err）を示した場合、
    //                  不正状態での続行を防ぐために、その場でプログラムを強制終了（パニック）させる。
    io::stdin().read_line(&mut input1).unwrap();

    // [データ型変換] 文字列データを計算可能な数値データへ変換する。
    // ・「: f64」: 変数num1が「64ビット浮動小数点数型」であることを明示する（型注釈）。
    // ・「.trim()」: 入力時に末尾に必ず付着する改行コード（\n や \r\n）および前後の余分な空白を除去する。
    // ・「.parse()」: 文字列を左辺で指定された型（f64）への変換を試みる。
    // ・「.unwrap()」: 文字列（例: "abc"）など数値化できない不正入力でparseが失敗（Err）した場合、
    //                  後続の計算バグを防止するため、ここでプログラムを安全にパニック（強制終了）させる。
    let num1: f64 = input1.trim().parse().unwrap();


    // ------------------------------------------------------------------------
    // 仕様2: 演算子の入力と最適化
    // ------------------------------------------------------------------------
    
    // [画面出力] ユーザーに四則演算記号の入力を促す。
    println!("Enter the operator (+, -, *, /):");

    // [バッファ確保] 演算子文字列を格納するための可変バッファを生成する。
    let mut op = String::new();

    // [標準入力の実行] 入力された演算子記号をバッファに読み込み、エラー時はパニックさせる。
    io::stdin().read_line(&mut op).unwrap();

    // [データのクレンジングと再定義] 改行コードを除去した不変オブジェクトとして固定する。
    // ・「let op =」: すでに存在する変数「mut op」と同名で変数を再宣言（シャドーイング）する。
    //                 これにより、以降の処理では古い「改行付き・可変」の変数へのアクセスを遮断する。
    // ・「op.trim()」: 末尾の改行コードを排除し、純粋な演算子記号のみの文字列スライス（&str）を抽出する。
    let op = op.trim();


    // ------------------------------------------------------------------------
    // 仕様3: 2つ目の数値の入力とデータ変換
    // ------------------------------------------------------------------------
    
    // [仕様概要] 仕様1（1つ目の数値入力）と完全に同一のロジック。
    //            2つ目の計算対象となる数値を安全に取得し、f64型として変数num2に束縛する。
    println!("Enter the second number:");
    let mut input2 = String::new();
    io::stdin().read_line(&mut input2).unwrap();
    let num2: f64 = input2.trim().parse().unwrap();


    // ------------------------------------------------------------------------
    // 仕様4: 条件分岐（条件付きパターンマッチング）と計算実行
    // ------------------------------------------------------------------------
    
    // [条件分岐の設計] 入力された演算子に応じて処理を完全に分離し、結果を直接代入する。
    // ・「let result = match op」: Rustのmatchは「式（Expression）」であるため、
    //                            各ケース（アーム）が評価した最終的な値を、変数resultへダイレクトに代入する。
    let result = match op {
        
        // ケース+: 足し算
        // [仕様] opが"+"と一致した場合、num1とnum2を加算した結果をmatch式の戻り値として返す。
        "+" => num1 + num2,
        
        // ケース-: 引き算
        // [仕様] opが"-"と一致した場合、num1からnum2を減算した結果をmatch式の戻り値として返す。
        "-" => num1 - num2,
        
        // ケース*: 掛け算
        // [仕様] opが"*"と一致した場合、num1とnum2を乗算した結果をmatch式の戻り値として返す。
        "*" => num1 * num2,
        
        // ケース/: 割り算（例外処理付き）
        // [仕様] opが"/"と一致した場合、ゼロ除算（0での割り算）を検知する防御ロジックを実行する。
        "/" => {
            // [ゼロ除算チェック] 2つ目の数値（分母）が浮動小数点数の「0.0」と等しいか判定する。
            if num2 == 0.0 {
                // 数学的な不正処理を防止するため、エラーメッセージを出力する。
                println!("You can't do 0 devine");
                // 「return」により、これ以降の計算や最終結果の出力をスキップし、
                // main関数自体の実行をこの時点で即座に終了（早期リターン）させる。
                return;
            }
            // [計算実行] 分母が0でないことが保証されたため、除算を実行する。
            // ※行末にセミコロン（;）がないため、この計算結果がこの波括弧ブロック「{ }」の
            //   最終的な返り値（評価値）となり、そのままmatch式へと渡される。
            num1 / num2
        }
        
        // デフォルトケース: 例外的な不正入力の検知
        // [仕様] 上記の「+」「-」「*」「/」のいずれのパターンにも合致しなかったすべてのケースを捕捉する。
        // ・「_」: ワイルドカードパターン（C言語のdefaultに相当）。Rustのmatch式は
        //          起こりうるすべての選択肢を網羅（網羅性の保証）しないとコンパイルエラーになるため必須。
        _ => {
            // 無効な演算子が入力された旨を画面に通知する。
            println!("Invalid input. Please try again");
            // プログラムの不正続行を防ぐため、main関数をここで終了させる。
            return;
        }
    }; // ※変数resultへの「代入文（let）」を締めくくるための文末セミコロン。


    // ------------------------------------------------------------------------
    // 仕様5: 最終結果の画面出力
    // ------------------------------------------------------------------------
    
    // [画面出力] 計算の全プロセスと結果をフォーマット整形して画面に表示する。
    // ・「{}」: プレースホルダー（埋め込み枠）。第2引数以降に指定された変数の値
    //          （num1, op, num2, result）が、左から順番に文字として埋め込まれて出力される。
    println!("Result: {} {} {} = {}", num1, op, num2, result);

} // プログラム（main関数）の終了

